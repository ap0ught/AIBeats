P = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(P / "ng" / "stages")); sys.path.insert(0, str(P))
import a56_common as C  # noqa
from ng.inputs import read_inputs  # noqa
XR = [0x0A,0x0A,0x14,0x0A,0x0A,0x10,0x10,0x0A,0x14,0x14,0x0A,0x0C,0x0C,0x0C,0x0C,0x14,0x14,0x14,0x14,0x0C,0x0C,0x14,0x14,0x0A,0x0A,0x0A,0x0A,0x0A,0x0A,0x0C,0x0A,0x0A,0x16,0x16,0x16,0x0C,0x0A,0x0A,0x0A,0x0A,0x0A,0x0A,0x0C,0x0A,0x0A,0x0A,0x0A,0x14,0x0A,0x14,0x14,0x14,0x14,0x0A,0x0A,0x0A,0x0A,0x0A,0x14,0x14,0x0A,0x0A,0x0C,0x0C,0x00,0x00,0x00,0x00,0x00,0x18,0x18,0x18,0x1C,0x18,0x0A,0x0A,0x0A,0x0A,0x1C,0x1C,0x1C,0x1C,0x18,0x18,0x0C,0x14,0x14,0x14,0x0C,0x10,0x10,0x18,0x18,0x18,0x18,0x18,0x10,0x10,0x10,0x0C,0x10,0x18,0x10,0x18,0x00,0x10,0x18,0x18,0x1C,0x20,0x20,0x1C,0x1C,0x10,0x10,0x10,0x10,0x10,0x10,0x0C,0x00,0x00,0x00,0x00,0x18,0x18,0x10,0x10,0x10,0x10,0x18,0x10,0x1C,0x10]
