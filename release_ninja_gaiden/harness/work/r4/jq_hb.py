src = sys.argv[1]
n = int(sys.argv[2]) if len(sys.argv) > 2 else 10**6
rows0 = list(read_inputs(P / src))[:n]
hist = list(read_inputs(P / "logs/a56_6-4a_b11.inputs.txt"))[-1700:] + [()] * 151
e = C.open_emu("r4_jqhb.log")
try:
    from ng.mode import TICKS
    e.tick(TICKS)
    F = dict(e.fields)
    F.update(jx=0x467, jy=0x487, jmov=0x43F, a83=0x83, yrad=0x90, jst=0x49F)
    e.set_fields(F)
    s0 = e.load("tmp/a56r2_64b_control")
    en = C.Enforcer(hist)
    rr = [en.emit(r, retry=0) for r in rows0]
    tr = C.play_trace(e, rr)
    prev = s0
    for i, t in enumerate(tr):
        hit = t["boss_real"] < prev["boss_real"]
        sw = t["a83"] in (7, 0x0A)
        pred = ""
        if sw:
            x, y, yr = t["x"], t["y"], t["yrad"]
            if t["rflags"] & 0x40:
                bx0, bx1 = x - 32, x
            else:
                bx0, bx1 = x, x + 32
            by0, by1 = y - yr, y - yr + 16
            m = t["jmov"]
            jx0, jx1, jy0, jy1 = t["jx"] - XR[m], t["jx"] + XR[m], t["jy"] - YR[m], t["jy"]
            ov = bx0 <= jx1 and bx1 >= jx0 and by0 <= jy1 and by1 >= jy0
            pred = f"PRED{int(ov)}"
        if sw or hit or i % 10 == 0:
            print(i + 1, "R", t["x"], t["y"], "a83", t["a83"], "f84", hex(t["rflags"]), "yrad", t["yrad"], "J", t["jx"], t["jy"],
                  "mov", t["jmov"], "bhp", t["boss_real"], "hp", t["hp"], "HIT" if hit else "", pred, "row", rr[i])
        prev = t
finally:
    e.close()
